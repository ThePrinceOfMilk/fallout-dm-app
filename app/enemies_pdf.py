# Prints "Fallout Enemies (for review).json" as a PDF, grouped by faction, so it can be read before importing.
# Run from app/: python enemies_pdf.py (needs reportlab)
import json, os
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from xml.sax.saxutils import escape as esc

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
rows = json.load(open(os.path.join(ROOT, "Fallout Enemies (for review).json"), encoding="utf8"))
added = set(json.load(open(os.path.join(HERE, "tests", "new_enemies.json"), encoding="utf8")))
rows = [e for e in rows if not e.get("test")]
new = [e for e in rows if e["n"] in added]; work = [e for e in rows if e["n"] not in added]

ss = getSampleStyleSheet()
H1 = ParagraphStyle("H1x", parent=ss["Heading1"], fontSize=17, spaceAfter=4, textColor=colors.HexColor("#0b5a2a"))
H2 = ParagraphStyle("H2x", parent=ss["Heading2"], fontSize=12, spaceBefore=9, spaceAfter=3, textColor=colors.HexColor("#0b5a2a"))
P = ParagraphStyle("Px", parent=ss["BodyText"], fontSize=9.5, leading=12.5, spaceAfter=4)
S = ParagraphStyle("Sx", parent=P, fontSize=8, leading=9.6, spaceAfter=0)
B = ParagraphStyle("Bx", parent=S, fontName="Helvetica-Bold")
LETTERS = "SPECIAL"
def special(e):
    sp = e.get("special") or []
    return " ".join(f"{LETTERS[i]}{v}" for i, v in enumerate(sp) if v is not None) or "-"
def skills(e):
    return " ".join(f"{k} {v}" for k, v in (e.get("skills") or {}).items()) or "-"
def toughness(e):
    if not e.get("mob"): return "from SPECIAL"
    return f"HP {e.get('hp', '?')} DT {e.get('dt', 0)} AP {e.get('ap', '?')}"
def weapons(e):
    w = [x for x in (e.get("w1"), e.get("w2")) if x]
    w = list(dict.fromkeys(w))
    return ", ".join(w) if w else "generated by tier"
HEAD = ["Name", "Tier", "XP", "Caps", "Toughness", "SPECIAL", "Skills", "Weapons"]
W = [1.75, 0.35, 0.35, 0.55, 1.05, 1.5, 1.6, 2.0]
def table(list_):
    data = [[Paragraph(x, B) for x in HEAD]] + [[Paragraph(esc(str(x)), S) for x in (e["n"], e.get("tier", ""), e.get("xp", ""), e.get("caps", "") or "-", toughness(e), special(e), skills(e), weapons(e))] for e in sorted(list_, key=lambda x: (x.get("tier", 0), x["n"]))]
    t = Table(data, colWidths=[w * inch for w in W], repeatRows=1)
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#d9efe0")), ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#9ab8a4")), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2), ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3)]))
    return t
def groups(list_):
    g = {}
    for e in list_: g.setdefault(e.get("faction", "Unaligned"), []).append(e)
    return g

story = [Paragraph("Fallout Enemies", H1)]
story.append(Paragraph(f"{len(new)} new enemies and {len(work)} workbook enemies with factions assigned. All of these are in the app. New enemies' skills and SPECIAL are built from the workbook's own templates. Workbook test rows are left out of this list. A dash under Caps means none. People's HP, AP and DT come from their SPECIAL and tier, while creatures have fixed numbers.", P))
story.append(Paragraph("Skills: BAR Barter, EW Energy Weapons, EXP Explosives, SG Small Guns, BG Big Guns, LPK Lockpick, MED Medicine, MW Melee Weapons, REP Repair, SCI Science, SNK Sneak, SPE Speech, SUR Survival.", P))
story.append(Paragraph("Part 1: New enemies", H1))
for f, lst in groups(new).items():
    story.append(Paragraph(f"{esc(f)} ({len(lst)})", H2)); story.append(table(lst))
story.append(Paragraph("Part 2: Workbook enemies, with the faction each was given", H1))
g = groups(work)
for f in sorted(g, key=lambda x: (x == "Unaligned", x)):
    story.append(Paragraph(f"{esc(f)} ({len(g[f])})", H2)); story.append(table(g[f]))
def foot(c, d):
    c.saveState(); c.setFont("Helvetica", 8); c.setFillColor(colors.grey); c.drawRightString(landscape(letter)[0] - 0.5 * inch, 0.35 * inch, f"Page {d.page}"); c.restoreState()
out = os.path.join(ROOT, "Fallout Enemies (for review).pdf")
SimpleDocTemplate(out, pagesize=landscape(letter), leftMargin=0.45 * inch, rightMargin=0.45 * inch, topMargin=0.5 * inch, bottomMargin=0.55 * inch, title="Fallout Enemies").build(story, onFirstPage=foot, onLaterPages=foot)
print(len(new), "new,", len(work), "workbook")
